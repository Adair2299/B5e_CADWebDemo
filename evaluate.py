"""Evaluate held-out commands and optional state-aware execution fixtures."""
import argparse
import json
from copy import deepcopy
from cad_schema import SCHEMAS, parse_command, canonical
from data_utils import load_pairs, question_key
from executor import Executor

METRICS = ['intent_accuracy', 'argument_accuracy', 'exact_command_accuracy',
           'valid_command_rate', 'execution_success_rate']

def evaluate_cases(cases, predict):
    """Argument accuracy is exact equality of all non-command fields / all cases.

    Execution success means no exception in the supplied pre-state, regardless
    of correctness. Execution is null when no explicit fixture is supplied.
    Every fixture is independent and is replayed identically for gold/prediction.
    """
    totals = {name: dict(n=0, intent=0, argument=0, exact=0, valid=0, executed=0, execution_cases=0) for name in SCHEMAS}
    details = []
    for case in cases:
        gold = parse_command(case['answer'])
        row = totals[gold['command']]
        row['n'] += 1
        executor = None
        if 'setup' in case:
            executor = Executor()
            gold_executor = Executor()
            for command in case['setup']:
                executor.execute(command)
                gold_executor.execute(command)
            # Invalid gold fixtures are data errors, not model failures.
            gold_executor.execute(gold)
            row['execution_cases'] += 1
        detail = {'question': case['question'], 'gold': gold}
        try:
            raw = predict(case['question'])
            detail['prediction'] = raw
            # Intent/argument measurements also include parseable but invalid commands.
            try:
                parsed = json.loads(raw)
                if isinstance(parsed, dict):
                    row['intent'] += parsed.get('command') == gold['command']
                    row['argument'] += {k: v for k, v in parsed.items() if k != 'command'} == {k: v for k, v in gold.items() if k != 'command'}
            except (ValueError, TypeError):
                pass
            pred = parse_command(raw)
            row['valid'] += 1
            row['exact'] += pred == gold
            if executor is not None:
                executor.execute(pred)
                row['executed'] += 1
        except (ValueError, TypeError, RuntimeError) as exc:
            detail['error'] = str(exc)
        details.append(detail)
    def rates(row):
        n = row['n']
        return {'count': n, 'intent_accuracy': row['intent'] / n if n else None,
                'argument_accuracy': row['argument'] / n if n else None,
                'exact_command_accuracy': row['exact'] / n if n else None,
                'valid_command_rate': row['valid'] / n if n else None,
                'execution_success_rate': row['executed'] / row['execution_cases'] if row['execution_cases'] else None,
                'execution_cases': row['execution_cases']}
    overall = {key: sum(row[key] for row in totals.values()) for key in next(iter(totals.values()))}
    return {'overall': rates(overall), 'by_command': {name: rates(row) for name, row in totals.items()}, 'details': details}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', default='cad_model.pt')
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--data', help='Held-out question,answer CSV; execution is not measured.')
    source.add_argument('--split-file', help='cad_splits.json generated by training; uses test only.')
    source.add_argument('--cases', help='JSON list with question, answer (JSON string), setup (list of commands).')
    parser.add_argument('--output', default='evaluation.json')
    args = parser.parse_args(args=["--split-file", "cad_splits.json"])
    from inference import Predictor
    predictor = Predictor(args.checkpoint)
    if args.data:
        cases = [dict(question=q, answer=a) for q, a in load_pairs([args.data])]
    elif args.split_file:
        with open(args.split_file, encoding='utf-8') as handle:
            cases = [dict(question=q, answer=a) for q, a in json.load(handle)['test']]
    else:
        with open(args.cases, encoding='utf-8') as handle:
            cases = json.load(handle)
    if not cases:
        parser.error('Empty evaluation set.')
    import torch
    checkpoint = torch.load(args.checkpoint, map_location='cpu', weights_only=True)
    seen = set(checkpoint.get('train_questions', [])) | set(checkpoint.get('validation_questions', []))
    if any(question_key(c['question']) in seen for c in cases):
        parser.error('Evaluation questions overlap training or validation.')
    report = evaluate_cases(cases, predictor.predict)
    with open(args.output, 'w', encoding='utf-8') as handle:
        json.dump(report, handle, indent=2)
    print(json.dumps(report['overall'], indent=2))

if __name__ == '__main__':
    main()
